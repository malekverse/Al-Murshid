// Release builds may fetch over plain HTTP from this phone itself only: localhost, and 10.0.2.2
// (the emulator's name for the computer). That lets a release build on an emulator download mushaf
// page fonts from the web dev server (`adb reverse tcp:3000 tcp:3000`) before an HTTPS asset CDN
// exists. Every other host still needs HTTPS. Debug builds keep plain HTTP everywhere, as React
// Native's own debug manifest allows, so the dev client reaches Metro on the LAN. See
// docs/DECISIONS.md.
const fs = require('fs');
const path = require('path');
const { withAndroidManifest, withDangerousMod } = require('expo/config-plugins');

const NAME = 'network_security_config';

const release = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by plugins/with-local-cleartext.js -->
<network-security-config>
  <base-config cleartextTrafficPermitted="false" />
  <domain-config cleartextTrafficPermitted="true">
    <domain includeSubdomains="false">localhost</domain>
    <domain includeSubdomains="false">10.0.2.2</domain>
  </domain-config>
</network-security-config>
`;

const debug = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by plugins/with-local-cleartext.js -->
<network-security-config>
  <base-config cleartextTrafficPermitted="true" />
</network-security-config>
`;

module.exports = function withLocalCleartext(config) {
  config = withAndroidManifest(config, (cfg) => {
    const app = cfg.modResults.manifest.application?.[0];
    if (app) app.$['android:networkSecurityConfig'] = `@xml/${NAME}`;
    return cfg;
  });
  return withDangerousMod(config, [
    'android',
    (cfg) => {
      const src = path.join(cfg.modRequest.platformProjectRoot, 'app', 'src');
      for (const [variant, body] of [
        ['release', release],
        ['debug', debug],
      ]) {
        const dir = path.join(src, variant, 'res', 'xml');
        fs.mkdirSync(dir, { recursive: true });
        fs.writeFileSync(path.join(dir, `${NAME}.xml`), body);
      }
      return cfg;
    },
  ]);
};
