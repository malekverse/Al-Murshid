// Generates the Tailwind v4 theme for both apps from the TypeScript tokens.
//   pnpm --filter @murshid/tokens build    -> writes generated/*.css
//   pnpm --filter @murshid/tokens check    -> fails if generated/*.css is stale (CI)

import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import {
  colors,
  cssName,
  cubicBezierCss,
  duration,
  easing,
  fonts,
  glassBlur,
  layout,
  radius,
  shadow,
  sky,
  starlight,
  touchTarget,
  typeScale,
  type ColorTokens,
  type TypeMetrics,
} from '../src/index';

const HEADER = '/* Generated by packages/tokens/scripts/generate.ts. Do not edit by hand. */\n';
const rem = (px: number) => `${+(px / 16).toFixed(4)}rem`;

function colorVars(tokens: ColorTokens, indent: string): string[] {
  return Object.entries(tokens).map(([k, v]) => `${indent}--color-${cssName(k)}: ${v};`);
}

function skyVars(indent: string): string[] {
  return Object.entries(sky)
    .flatMap(([period, stop]) => [
      `${indent}--color-sky-${period}-top: ${stop.top};`,
      `${indent}--color-sky-${period}-bottom: ${stop.bottom};`,
    ])
    .concat(`${indent}--color-starlight: ${starlight};`);
}

/** `--text-<name>` utilities. Latin roles keep their name; Arabic roles get an `ar-` prefix. */
function textVars(
  indent: string,
  opts: { withWeight: boolean; absoluteLineHeight: boolean },
): string[] {
  const out: string[] = [];
  const emit = (name: string, m: TypeMetrics, weight: number) => {
    out.push(`${indent}--text-${name}: ${rem(m.size)};`);
    out.push(
      `${indent}--text-${name}--line-height: ${
        opts.absoluteLineHeight ? rem(Math.round(m.size * m.lineHeight)) : m.lineHeight
      };`,
    );
    if (opts.withWeight) out.push(`${indent}--text-${name}--font-weight: ${weight};`);
  };
  for (const [role, def] of Object.entries(typeScale)) {
    const name = cssName(role).replace(/(\d)/, '-$1'); // title1 -> title-1
    if ('latin' in def) emit(name, def.latin, def.weight);
    const arabicName = role === 'quran' || role === 'dhikr' ? name : `ar-${name}`;
    emit(arabicName, def.arabic, def.weight);
  }
  return out;
}

function shapeVars(indent: string): string[] {
  return [
    ...Object.entries(radius).map(([k, v]) => `${indent}--radius-${k}: ${rem(v)};`),
    `${indent}--spacing-touch: ${rem(touchTarget)};`,
  ];
}

function web(): string {
  const i = '  ';
  return [
    HEADER,
    '/* Dark theme follows [data-theme="dark"] on <html>, set before paint by the theme script. */',
    '@custom-variant dark (&:where([data-theme=dark], [data-theme=dark] *));',
    '',
    '@theme {',
    '  /* Reset Tailwind defaults so only Quiet Light tokens exist as utilities. */',
    `${i}--color-*: initial;`,
    `${i}--font-*: initial;`,
    `${i}--text-*: initial;`,
    `${i}--radius-*: initial;`,
    `${i}--shadow-*: initial;`,
    `${i}--ease-*: initial;`,
    '',
    ...colorVars(colors.light, i),
    ...skyVars(i),
    '',
    `${i}--font-ui: ${fonts.web.ui};`,
    `${i}--font-sacred: ${fonts.web.sacred};`,
    `${i}--font-quran: ${fonts.web.quran};`,
    `${i}--default-font-family: var(--font-ui);`,
    '',
    ...textVars(i, { withWeight: true, absoluteLineHeight: false }),
    '',
    ...shapeVars(i),
    ...Object.entries(shadow).map(([k, v]) => `${i}--shadow-${k}: ${v};`),
    ...Object.keys(easing).map(
      (k) => `${i}--ease-${k}: ${cubicBezierCss(k as keyof typeof easing)};`,
    ),
    `${i}--blur-glass: ${glassBlur}px;`,
    `${i}--container-reading: ${rem(layout.reading)};`,
    `${i}--container-page: ${rem(layout.page)};`,
    '}',
    '',
    ':root {',
    `${i}color-scheme: light;`,
    ...Object.entries(duration).map(([k, v]) => `${i}--duration-${k}: ${v}ms;`),
    '}',
    '',
    '/* Explicit light scope, so a light island can sit inside a dark page (glass over a bright sky). */',
    '[data-theme=light] {',
    `${i}color-scheme: light;`,
    ...colorVars(colors.light, i),
    '}',
    '',
    '[data-theme=dark] {',
    `${i}color-scheme: dark;`,
    ...colorVars(colors.dark, i),
    ...Object.keys(shadow).map((k) => `${i}--shadow-${k}: 0 0 #0000;`),
    '}',
    '',
  ].join('\n');
}

function native(): string {
  const i = '  ';
  const ii = '      ';
  const weightVars = Object.entries(fonts.native.ui).map(([w, family]) => {
    const suffix = w === '400' ? '' : w === '500' ? '-medium' : '-semibold';
    return `${i}--font-ui${suffix}: ${family};`;
  });
  return [
    HEADER,
    '/* Uniwind theme: light and dark variables switch with Uniwind.setTheme(). */',
    '@layer theme {',
    '  :root {',
    '    @variant light {',
    ...colorVars(colors.light, ii),
    '    }',
    '    @variant dark {',
    ...colorVars(colors.dark, ii),
    '    }',
    '  }',
    '}',
    '',
    '@theme {',
    ...skyVars(i),
    '',
    '  /* One family per weight on native, so Arabic never gets synthetic bold. */',
    ...weightVars,
    `${i}--font-sacred: ${fonts.native.sacred};`,
    `${i}--font-quran: ${fonts.native.quran};`,
    '',
    ...textVars(i, { withWeight: false, absoluteLineHeight: true }),
    '',
    ...shapeVars(i),
    ...Object.entries(shadow).map(([k, v]) => `${i}--shadow-${k}: ${v};`),
    '}',
    '',
  ].join('\n');
}

const outDir = join(dirname(fileURLToPath(import.meta.url)), '..', 'generated');
const files = { 'theme.web.css': web(), 'theme.native.css': native() };
const check = process.argv.includes('--check');
let stale = false;

mkdirSync(outDir, { recursive: true });
for (const [name, content] of Object.entries(files)) {
  const path = join(outDir, name);
  if (check) {
    let current = '';
    try {
      current = readFileSync(path, 'utf8');
    } catch {
      // missing counts as stale
    }
    if (current !== content) {
      console.error(`✗ ${name} is out of date. Run: pnpm --filter @murshid/tokens build`);
      stale = true;
    }
  } else {
    writeFileSync(path, content);
    console.log(`✓ wrote generated/${name}`);
  }
}
if (stale) process.exit(1);
if (check) console.log('✓ generated theme files are up to date');
