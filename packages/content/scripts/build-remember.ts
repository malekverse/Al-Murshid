// Builds remember/generated/ from the pinned HadeethEnc file (scripts/hadeethenc.ts): one small
// file per language and chapter, so the apps load a chapter at a time.
//
//   pnpm --filter @murshid/content remember          -> rewrites remember/generated
//   pnpm --filter @murshid/content remember:check    -> fails if it is stale (CI)
//
// Every hadith is shown whole, as published: only line endings and the spaces around a text are
// tidied. Arabic shows every hadith. English shows those HadeethEnc has translated, and French its
// own translations, then the English one (marked "en") where it has none yet (SPEC 10). A hadith
// with neither is left out of English and French until HadeethEnc translates it.

import { mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { rememberChapters, type RememberHadith } from '../src/remember-types';

const dir = fileURLToPath(new URL('../remember/', import.meta.url));
const outDir = dir + 'generated/';
const check = process.argv.includes('--check');

function assert(condition: unknown, message: string): asserts condition {
  if (!condition) throw new Error(message);
}

type Fields = Record<string, unknown>;
interface Source {
  retrieved: string;
  categories: { id: string; hadiths: string[] }[];
  hadiths: ({ id: string } & Record<'ar' | 'en' | 'fr', Fields | null>)[];
}
const source = JSON.parse(readFileSync(dir + 'source/hadeethenc.json', 'utf8')) as Source;
const byId = new Map(source.hadiths.map((h) => [h.id, h]));

const tidy = (value: unknown, what: string) => {
  assert(typeof value === 'string', `${what}: expected text`);
  const text = value.replace(/\r\n?/g, '\n').trim();
  assert(text.length > 0 && !/[<>]/.test(text), `${what}: empty or with markup`);
  return text;
};
const list = (value: unknown, what: string) => {
  assert(Array.isArray(value), `${what}: expected a list`);
  return value.map((v, i) => tidy(v, `${what} ${i + 1}`));
};
const meanings = (value: unknown, what: string) => {
  assert(Array.isArray(value), `${what}: expected a list`);
  return (value as { word: string; meaning: string }[]).map((m, i) => ({
    word: tidy(m.word, `${what} ${i + 1}`),
    meaning: tidy(m.meaning, `${what} ${i + 1}`),
  }));
};

function entry(id: string, locale: 'ar' | 'en' | 'fr'): RememberHadith | null {
  const h = byId.get(id);
  assert(h?.ar, `hadith ${id}: no Arabic`);
  const ar = h.ar;
  const what = `hadith ${id}`;
  const arabic = {
    text: tidy(ar.hadeeth, `${what} text`),
    attribution: tidy(ar.attribution, `${what} attribution`),
    grade: tidy(ar.grade, `${what} grade`),
    reference: tidy(ar.reference, `${what} reference`),
  };
  const lang = locale === 'ar' ? 'ar' : h[locale] ? locale : h.en ? 'en' : null;
  if (!lang) return null;
  const t = h[lang]!;
  // A translation repeats the Arabic it was made from: it must be the same hadith.
  if (lang !== 'ar')
    assert(
      tidy(t.hadeeth_ar, `${what} hadeeth_ar`) === arabic.text,
      `${what}: ${lang} is from another text`,
    );
  return {
    id,
    lang,
    title: tidy(t.title, `${what} title`),
    text: tidy(t.hadeeth, `${what} ${lang} text`),
    attribution: tidy(t.attribution, `${what} ${lang} attribution`),
    grade: tidy(t.grade, `${what} ${lang} grade`),
    explanation: tidy(t.explanation, `${what} ${lang} explanation`),
    hints: list(t.hints, `${what} ${lang} hints`),
    ...(lang === 'ar' ? { meanings: meanings(ar.words_meanings, `${what} meanings`) } : {}),
    arabic,
    link: `https://hadeethenc.com/${lang}/browse/hadith/${id}`,
  };
}

const files = new Map<string, string>();
const put = (path: string, value: unknown) => files.set(path, JSON.stringify(value) + '\n');

for (const locale of ['ar', 'en', 'fr'] as const) {
  const index = [];
  for (const chapter of rememberChapters) {
    const category = source.categories.find((c) => c.id === chapter.hadeethEnc);
    assert(category, `chapter ${chapter.slug}: HadeethEnc ${chapter.hadeethEnc} missing`);
    const hadiths = category.hadiths
      .map((id) => entry(id, locale))
      .filter((h): h is RememberHadith => h !== null);
    put(`${locale}/${chapter.slug}.json`, hadiths);
    index.push({ slug: chapter.slug, count: hadiths.length });
  }
  put(`${locale}/index.json`, index);
}
put('version.json', { source: 'HadeethEnc.com', version: source.retrieved });

const chapterList = (locale: string) =>
  `{ ${rememberChapters
    .map((c) => `'${c.slug}': () => import('./${locale}/${c.slug}.json')`)
    .join(', ')} }`;
files.set(
  'loaders.js',
  [
    '// Generated by scripts/build-remember.ts. Do not edit.',
    'export const chapters = {',
    ...['ar', 'en', 'fr'].map((l) => `  ${l}: ${chapterList(l)},`),
    '};',
    'export const indexes = {',
    ...['ar', 'en', 'fr'].map((l) => `  ${l}: () => import('./${l}/index.json'),`),
    '};',
    '',
  ].join('\n'),
);

const existing = new Set<string>();
const walk = (path: string, prefix = '') => {
  for (const e of readdirSync(path, { withFileTypes: true })) {
    if (e.isDirectory()) walk(path + e.name + '/', prefix + e.name + '/');
    else existing.add(prefix + e.name);
  }
};
try {
  walk(outDir);
} catch {
  // Nothing generated yet.
}
existing.delete('loaders.d.ts'); // Written by hand.

if (check) {
  const stale = [...files].filter(([path, body]) => {
    try {
      return readFileSync(outDir + path, 'utf8') !== body;
    } catch {
      return true;
    }
  });
  const extra = [...existing].filter((p) => !files.has(p));
  if (stale.length || extra.length) {
    console.error('remember/generated is stale. Run: pnpm --filter @murshid/content remember');
    process.exit(1);
  }
  console.log(`remember/generated is up to date (${files.size} files).`);
} else {
  for (const p of existing) if (!files.has(p)) rmSync(outDir + p);
  for (const [path, body] of files) {
    mkdirSync(outDir + path.slice(0, path.lastIndexOf('/') + 1), { recursive: true });
    writeFileSync(outDir + path, body);
  }
  console.log(`Wrote ${files.size} files to remember/generated.`);
}
